#!/usr/bin/env bash
# install.sh - provision the whole vpn-stack on a fresh Debian/Ubuntu VPS.
#
# Idempotent: safe to re-run. Every step checks before it acts. Firewall state is
# backed up before anything is touched, so a failure is always recoverable.
#
#   sudo ./install.sh                       server only (WireGuard + AmneziaWG)
#   sudo ./install.sh --with-dns            + AdGuard Home and recursive unbound
#   sudo ./install.sh --with-hardening      + SSH/sysctl hardening and fail2ban
#   sudo ./install.sh --all                 everything
#   sudo ./install.sh --dry-run             show what would change, change nothing
#
set -euo pipefail

WITH_DNS=0; WITH_HARDENING=0; DRY_RUN=0
for a in "$@"; do
  case "$a" in
    --with-dns)       WITH_DNS=1 ;;
    --with-hardening) WITH_HARDENING=1 ;;
    --all)            WITH_DNS=1; WITH_HARDENING=1 ;;
    --dry-run)        DRY_RUN=1 ;;
    -h|--help)        sed -n '2,12p' "$0"; exit 0 ;;
    *) echo "unknown flag: $a" >&2; exit 1 ;;
  esac
done
export DRY_RUN

source "$(dirname "$0")/scripts/lib.sh"

# ================================================================ 0. recon
echo
c_blue "0. recon"
VIRT=$(systemd-detect-virt 2>/dev/null || echo "none")
info "virt:       $VIRT"
info "kernel:     $(uname -r)"
info "os:         $(. /etc/os-release && echo "$PRETTY_NAME")"
info "wan iface:  $(ip route show default | awk '{print $5; exit}')"

if [ "$VIRT" = "docker" ] || [ "$VIRT" = "lxc" ]; then
  die "kernel WireGuard needs a real VM. Use a KVM/bare-metal instance."
fi
[ -e /dev/net/tun ] || die "/dev/net/tun missing - kernel WireGuard cannot work here"

PUBIP4=$(public_ip4)
[ -n "$PUBIP4" ] || die "could not determine the public IPv4"
info "public ipv4: $PUBIP4"
need_root

# ================================================================ 1. firewall backup
echo
c_blue "1. back up firewall state (rollback insurance)"
BK="$HOME/iptables-backup-$(date +%F-%H%M).rules"
if [ "$DRY_RUN" = "1" ]; then
  info "[dry-run] would write $BK"
else
  asroot iptables-save > "$BK" 2>/dev/null || true
  ok "saved $BK"
  info "restore with: sudo iptables-restore < $BK"
fi

# ================================================================ 2. packages
echo
c_blue "2. packages"
if [ "$DRY_RUN" = "0" ]; then
  asroot env DEBIAN_FRONTEND=noninteractive apt-get update -qq
  asroot env DEBIAN_FRONTEND=noninteractive apt-get install -y -qq wireguard wireguard-tools qrencode
  asroot modprobe wireguard && ok "wireguard kernel module loaded"
else
  info "[dry-run] apt-get install wireguard wireguard-tools qrencode"
fi
mkdir -p "$KEY_DIR"; chmod 700 "$KEY_DIR"
mkdir -p "$OUT_DIR"; chmod 700 "$OUT_DIR"

# ================================================================ 3. keys
echo
c_blue "3. keys"
if [ -f "$KEY_DIR/server.key" ]; then
  ok "server keypair already exists - keeping it"
else
  gen_keypair server wg
  ok "generated server keypair"
fi

# ================================================================ 4. forwarding
echo
c_blue "4. ip forwarding"
if [ "$DRY_RUN" = "0" ]; then
  printf 'net.ipv4.ip_forward=1\nnet.ipv6.conf.all.forwarding=1\n' > /tmp/99-wireguard.conf
  asroot install -m 644 -o root -g root /tmp/99-wireguard.conf /etc/sysctl.d/99-wireguard.conf
  asroot sysctl -q --system
  ok "ip_forward=$(sysctl -n net.ipv4.ip_forward)  ipv6.forwarding=$(sysctl -n net.ipv6.conf.all.forwarding)"
fi

# ================================================================ 5. server config
echo
c_blue "5. server config"
CFG="$WG_DIR/$WG_IFACE.conf"
if [ -f "$CFG" ]; then
  ok "$CFG exists - leaving it alone (use add-device.sh to add peers)"
else
  WAN=$(ip route show default | awk '{print $5; exit}')
  if [ "$DRY_RUN" = "0" ]; then
    asroot mkdir -p "$WG_DIR"
    asroot tee "$CFG" > /dev/null <<EOF
# vpn-stack server - generated by install.sh
# IPv6 is included from the start: an IPv4-only tunnel silently leaks IPv6.
[Interface]
Address    = ${WG_SUBNET4%.*}.1/24, ${WG_SUBNET6%::*}::1/64
ListenPort = $WG_PORT
PrivateKey = $(cat "$KEY_DIR/server.key")

PostUp   = iptables -I FORWARD 1 -i %i -j ACCEPT; iptables -I FORWARD 1 -o %i -j ACCEPT; iptables -t nat -A POSTROUTING -s $WG_SUBNET4 -o $WAN -j MASQUERADE
PostUp   = ip6tables -I FORWARD 1 -i %i -j ACCEPT; ip6tables -I FORWARD 1 -o %i -j ACCEPT; ip6tables -t nat -A POSTROUTING -s $WG_SUBNET6 -o $WAN -j MASQUERADE
PostDown = iptables -D FORWARD -i %i -j ACCEPT; iptables -D FORWARD -o %i -j ACCEPT; iptables -t nat -D POSTROUTING -s $WG_SUBNET4 -o $WAN -j MASQUERADE
PostDown = ip6tables -D FORWARD -i %i -j ACCEPT; ip6tables -D FORWARD -o %i -j ACCEPT
EOF
    asroot chmod 600 "$CFG"
    ok "wrote $CFG (wan iface: $WAN)"
  fi
fi

# ================================================================ 6. firewall
echo
c_blue "6. firewall"
if [ "$DRY_RUN" = "0" ] && command -v ufw >/dev/null && ufw status 2>/dev/null | grep -q "Status: active"; then
  asroot ufw allow "$WG_PORT"/udp comment 'WireGuard' >/dev/null 2>&1 || true
  ok "ufw: opened $WG_PORT/udp"
  warn "if your provider has a CLOUD firewall too (Hetzner/DO/AWS), open it there as well"
  warn "a cloud firewall sits in front of the VM and is invisible from inside"
else
  info "[dry-run] ufw allow $WG_PORT/udp"
fi

# ================================================================ 7. bring up
echo
c_blue "7. bring up + persist"
if [ "$DRY_RUN" = "0" ]; then
  asroot systemctl enable "wg-quick@$WG_IFACE" >/dev/null 2>&1 || true
  if ip link show "$WG_IFACE" >/dev/null 2>&1; then
    ok "$WG_IFACE already up"
  else
    asroot systemctl start "wg-quick@$WG_IFACE"
    ok "$WG_IFACE started"
  fi
  info "enabled at boot: $(systemctl is-enabled "wg-quick@$WG_IFACE" 2>&1)"
fi

# ================================================================ 8. amneziawg
echo
c_blue "8. AmneziaWG (obfuscated transport)"
if command -v awg >/dev/null 2>&1; then
  ok "already installed"
else
  warn "Install manually from the project's PPA - it is an out-of-tree DKMS module and"
  warn "the module must be built for the kernel that will BOOT, not just the running one:"
  echo
  echo "    sudo add-apt-repository -y ppa:amnezia/ppa"
  echo "    sudo apt-get update"
  echo "    sudo apt-get install -y amneziawg amneziawg-tools amneziawg-dkms"
  echo "    # build for the RUNNING kernel"
  echo "    sudo apt-get install -y linux-headers-\$(uname -r)"
  echo "    sudo dkms install amneziawg/1.0.0 -k \$(uname -r) --force"
  echo "    sudo depmod -a \$(uname -r)     # required, or modprobe cannot find it"
  echo "    # then verify EVERY kernel that has an image in /boot"
  echo "    for k in \$(ls /lib/modules/); do sudo modinfo -k \$k amneziawg >/dev/null 2>&1 \\"
  echo "      && echo \"\$k OK\" || echo \"\$k MISSING\"; done"
  echo
fi

# ================================================================ 9. dns
if [ "$WITH_DNS" = "1" ]; then
  echo
  c_blue "9. DNS (AdGuard Home + recursive unbound)"
  warn "interactive: AdGuard Home needs a first-run admin password."
  warn "See docs/dns.md for the exact setup, including the two traps:"
  echo
  echo "    - AdGuard v1.0.0's config migrator nests bootstrap_dns into a"
  echo "      list-of-lists that its own parser then rejects. Flatten it."
  echo "    - unbound and AdGuard each set a trust anchor (or bind :53)."
  echo "      Do not declare auto-trust-anchor-file twice - unbound refuses to start."
  echo
fi

# ================================================================ 10. hardening
if [ "$WITH_HARDENING" = "1" ]; then
  echo
  c_blue "10. hardening"
  if [ "$DRY_RUN" = "0" ]; then
    cat > /tmp/99-hardening.conf <<'EOF'
kernel.sysrq = 0
net.ipv4.conf.all.log_martians = 1
net.ipv4.conf.all.accept_source_route = 0
net.ipv4.conf.all.accept_redirects = 0
net.ipv4.conf.all.send_redirects = 0
net.ipv4.tcp_syncookies = 1
net.ipv4.tcp_rfc1337 = 1
net.ipv6.conf.all.accept_redirects = 0
net.ipv6.conf.all.accept_source_route = 0
EOF
    asroot install -m 644 -o root -g root /tmp/99-hardening.conf /etc/sysctl.d/99-hardening.conf
    asroot sysctl -q --system
    ok "sysctl hardening applied"

    # Only touch sshd if password auth is ALREADY off - otherwise this locks you out.
    if sshd -T 2>/dev/null | grep -qi "^passwordauthentication no"; then
      cat > /tmp/99-vpn-hardening.conf <<'EOF'
X11Forwarding no
AllowAgentForwarding no
PermitUserEnvironment no
MaxAuthTries 3
MaxSessions 4
LoginGraceTime 30
ClientAliveInterval 300
ClientAliveCountMax 2
EOF
      asroot install -m 644 -o root -g root /tmp/99-vpn-hardening.conf /etc/ssh/sshd_config.d/99-vpn-hardening.conf
      if asroot sshd -t 2>/dev/null; then
        asroot systemctl reload ssh 2>/dev/null || asroot systemctl reload sshd 2>/dev/null || true
        ok "ssh hardened and reloaded"
      else
        asroot mv /etc/ssh/sshd_config.d/99-vpn-hardening.conf "/tmp/rejected.$(date +%s)"
        warn "sshd config invalid - reverted, sshd untouched"
      fi
    else
      warn "password auth is ON - skipping SSH hardening to avoid locking you out"
    fi

    asroot env DEBIAN_FRONTEND=noninteractive apt-get install -y -qq fail2ban
    cat > /tmp/jail.local <<'EOF'
[DEFAULT]
bantime  = 1h
findtime = 10m
maxretry = 5
backend  = systemd

[sshd]
enabled = true
port    = 22
mode    = aggressive
EOF
    asroot install -m 644 -o root -g root /tmp/jail.local /etc/fail2ban/jail.local
    asroot systemctl enable --now fail2ban >/dev/null 2>&1 || true
    ok "fail2ban active"
  fi
fi

# ================================================================ done
echo
c_blue "done"
echo
info "verify:      sudo ./scripts/status.sh"
info "add device:  sudo ./scripts/add-device.sh my-phone"
info "egress test: curl -4 --interface ${WG_SUBNET4%.*}.1 -s --max-time 10 ifconfig.me"
echo "               ^ should return THIS server's public IP ($PUBIP4)"
echo
warn "open $WG_PORT/udp in your provider's cloud firewall if you have one"
echo
